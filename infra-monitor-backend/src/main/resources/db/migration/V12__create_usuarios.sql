CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    papel VARCHAR(20) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    troca_senha_obrigatoria BOOLEAN NOT NULL DEFAULT TRUE,
    ultimo_login_em TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_usuarios PRIMARY KEY (id),
    CONSTRAINT ck_usuarios_nome_nao_vazio CHECK (btrim(nome) <> ''),
    CONSTRAINT ck_usuarios_email_nao_vazio CHECK (btrim(email) <> ''),
    CONSTRAINT ck_usuarios_papel CHECK (papel IN ('ADMIN', 'OPERADOR', 'VISUALIZADOR'))
);

-- A aplicacao normaliza e-mail para lowercase e este indice garante a regra
-- tambem para escrita concorrente ou direta no PostgreSQL.
CREATE UNIQUE INDEX uq_usuarios_email_lower ON usuarios (LOWER(email));
