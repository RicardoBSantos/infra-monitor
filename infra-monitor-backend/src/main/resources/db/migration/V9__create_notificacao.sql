-- Historico de tentativas de comunicacao dos eventos de incidente.
CREATE TABLE notificacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    incidente_id BIGINT NOT NULL,
    canal VARCHAR(20) NOT NULL,
    tipo_evento VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    tentativas INTEGER NOT NULL DEFAULT 0,
    mensagem TEXT NOT NULL,
    erro VARCHAR(1000),
    enviado_em TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_notificacao PRIMARY KEY (id),
    CONSTRAINT fk_notificacao_incidente FOREIGN KEY (incidente_id)
        REFERENCES incidente (id) ON DELETE RESTRICT,
    CONSTRAINT uq_notificacao_incidente_canal_evento UNIQUE (incidente_id, canal, tipo_evento),
    CONSTRAINT ck_notificacao_canal CHECK (canal IN ('TELEGRAM')),
    CONSTRAINT ck_notificacao_tipo_evento CHECK (tipo_evento IN ('INCIDENTE_ABERTO', 'INCIDENTE_FECHADO')),
    CONSTRAINT ck_notificacao_status CHECK (status IN ('PENDENTE', 'ENVIANDO', 'ENVIADA', 'FALHA')),
    CONSTRAINT ck_notificacao_tentativas_nao_negativas CHECK (tentativas >= 0),
    CONSTRAINT ck_notificacao_enviado_em CHECK (status <> 'ENVIADA' OR enviado_em IS NOT NULL)
);

CREATE INDEX ix_notificacao_incidente_id ON notificacao (incidente_id);
CREATE INDEX ix_notificacao_status_created_at ON notificacao (status, created_at DESC);
