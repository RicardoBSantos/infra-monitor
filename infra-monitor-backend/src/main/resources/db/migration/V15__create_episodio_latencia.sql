-- V15 - Episodios de latencia alta por monitor e sua ancoragem em notificacao.
--
-- Degradacao por latencia nao abre incidente: ate aqui ela so existia como projecao
-- de leitura do dashboard, sem estado e sem momento de transicao. Sem uma ancora
-- propria uma notificacao de latencia sairia a cada ciclo de ping acima do limiar.
-- O episodio e essa ancora: um por monitor enquanto durar a degradacao.
CREATE TABLE monitor_episodio_latencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    monitor_id BIGINT NOT NULL,
    iniciado_em TIMESTAMPTZ NOT NULL,
    encerrado_em TIMESTAMPTZ,
    -- O limiar e global e vem do ambiente; grava-lo mantem o episodio explicavel
    -- depois de uma troca de MONITORING_LATENCIA_DEGRADADA_MS.
    limiar_ms INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_monitor_episodio_latencia PRIMARY KEY (id),
    CONSTRAINT fk_monitor_episodio_latencia_monitor FOREIGN KEY (monitor_id)
        REFERENCES monitor (id) ON DELETE RESTRICT,
    CONSTRAINT ck_monitor_episodio_latencia_periodo CHECK (
        encerrado_em IS NULL OR encerrado_em >= iniciado_em
    ),
    CONSTRAINT ck_monitor_episodio_latencia_limiar CHECK (limiar_ms > 0)
);

-- Episodio aberto = encerrado_em IS NULL. Garante a regra sob concorrencia,
-- alem da validacao de negocio. Mesmo padrao de uq_janela_monitoramento_aberta.
CREATE UNIQUE INDEX uq_monitor_episodio_latencia_aberto
    ON monitor_episodio_latencia (monitor_id) WHERE encerrado_em IS NULL;

-- Atende o historico de um monitor e sua ordenacao padrao.
CREATE INDEX ix_monitor_episodio_latencia_monitor_iniciado_em
    ON monitor_episodio_latencia (monitor_id, iniciado_em DESC);

-- Notificacao passa a ter duas ancoras possiveis, sempre exatamente uma delas.
ALTER TABLE notificacao ALTER COLUMN incidente_id DROP NOT NULL;

ALTER TABLE notificacao ADD COLUMN episodio_latencia_id BIGINT;

ALTER TABLE notificacao ADD CONSTRAINT fk_notificacao_episodio_latencia
    FOREIGN KEY (episodio_latencia_id)
    REFERENCES monitor_episodio_latencia (id) ON DELETE RESTRICT;

ALTER TABLE notificacao ADD CONSTRAINT ck_notificacao_ancora_exclusiva
    CHECK (num_nonnulls(incidente_id, episodio_latencia_id) = 1);

-- CHECK nao se estende: e preciso recriar com os dois eventos novos.
ALTER TABLE notificacao DROP CONSTRAINT ck_notificacao_tipo_evento;
ALTER TABLE notificacao ADD CONSTRAINT ck_notificacao_tipo_evento CHECK (
    tipo_evento IN ('INCIDENTE_ABERTO', 'INCIDENTE_FECHADO',
                    'LATENCIA_ALTA', 'LATENCIA_NORMALIZADA')
);

-- Impede evento de incidente pendurado em episodio e vice-versa. Junto com
-- ck_notificacao_ancora_exclusiva fecha as duas direcoes.
ALTER TABLE notificacao ADD CONSTRAINT ck_notificacao_evento_coerente CHECK (
    (tipo_evento IN ('INCIDENTE_ABERTO', 'INCIDENTE_FECHADO') AND incidente_id IS NOT NULL)
    OR (tipo_evento IN ('LATENCIA_ALTA', 'LATENCIA_NORMALIZADA') AND episodio_latencia_id IS NOT NULL)
);

-- Irma de uq_notificacao_incidente_canal_evento: no maximo um LATENCIA_ALTA e um
-- LATENCIA_NORMALIZADA por episodio. UNIQUE trata NULLs como distintos, entao as
-- linhas ancoradas em incidente nao colidem aqui (nem as de latencia la).
ALTER TABLE notificacao ADD CONSTRAINT uq_notificacao_episodio_canal_evento
    UNIQUE (episodio_latencia_id, canal, tipo_evento);

CREATE INDEX ix_notificacao_episodio_latencia_id
    ON notificacao (episodio_latencia_id);
