-- V2 - Modulo de Inventario: unidade, tipo_equipamento e equipamento.
--
-- Escopo desta migration: apenas o cadastro estatico do inventario.
-- Monitoramento (monitor, medicao, incidente, notificacao, canal_alerta) NAO
-- pertence a este modulo e entra em versoes posteriores.
--
-- Convencoes de soft delete adotadas em todo o modulo:
--   ativo = FALSE            -> registro existe, porem esta desativado.
--   deleted_at IS NOT NULL   -> registro foi excluido logicamente.
-- Sao conceitos distintos: toda unicidade de negocio vale somente entre
-- registros nao excluidos (deleted_at IS NULL), permitindo recadastrar nome,
-- sigla, slug ou IP de um registro previamente excluido.


-- ---------------------------------------------------------------------------
-- unidade
-- ---------------------------------------------------------------------------
CREATE TABLE unidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(150) NOT NULL,
    sigla VARCHAR(30) NOT NULL,
    descricao TEXT,
    endereco VARCHAR(255),
    cidade VARCHAR(100),
    estado VARCHAR(2),
    latitude NUMERIC(9, 6),
    longitude NUMERIC(9, 6),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_unidade PRIMARY KEY (id),
    CONSTRAINT ck_unidade_nome_nao_vazio CHECK (btrim(nome) <> ''),
    CONSTRAINT ck_unidade_sigla_nao_vazia CHECK (btrim(sigla) <> ''),
    CONSTRAINT ck_unidade_latitude_faixa CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_unidade_longitude_faixa CHECK (longitude BETWEEN -180 AND 180),
    -- Meia coordenada nao localiza nada: ou as duas, ou nenhuma.
    CONSTRAINT ck_unidade_coordenadas_completas
        CHECK ((latitude IS NULL) = (longitude IS NULL))
);

-- Sigla unica entre registros nao excluidos. LOWER() mantem a comparacao
-- insensivel a maiusculas/minusculas tambem em operacoes concorrentes feitas
-- diretamente no PostgreSQL, sem depender da validacao da aplicacao.
CREATE UNIQUE INDEX uq_unidade_sigla ON unidade (LOWER(sigla)) WHERE deleted_at IS NULL;

-- Nome unico entre registros nao excluidos: regra ja vigente no cadastro de
-- unidades da aplicacao (existsByNomeIgnoreCase), preservada em nivel de banco.
CREATE UNIQUE INDEX uq_unidade_nome ON unidade (LOWER(nome)) WHERE deleted_at IS NULL;


-- ---------------------------------------------------------------------------
-- tipo_equipamento
-- ---------------------------------------------------------------------------
CREATE TABLE tipo_equipamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    slug VARCHAR(100) NOT NULL,
    descricao TEXT,
    icone VARCHAR(100),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_tipo_equipamento PRIMARY KEY (id),
    CONSTRAINT ck_tipo_equipamento_nome_nao_vazio CHECK (btrim(nome) <> ''),
    CONSTRAINT ck_tipo_equipamento_slug_nao_vazio CHECK (btrim(slug) <> '')
);

CREATE UNIQUE INDEX uq_tipo_equipamento_nome ON tipo_equipamento (LOWER(nome)) WHERE deleted_at IS NULL;

CREATE UNIQUE INDEX uq_tipo_equipamento_slug ON tipo_equipamento (LOWER(slug)) WHERE deleted_at IS NULL;


-- ---------------------------------------------------------------------------
-- equipamento
-- ---------------------------------------------------------------------------
-- Atributos de monitoramento (status ICMP, latencia, ultimo ping, timeout,
-- intervalo, tentativas) pertencem ao dominio monitor e NAO existem aqui.
-- fabricante, modelo e localizacao permanecem como atributos simples: sem
-- normalizacao nesta primeira versao.
CREATE TABLE equipamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    unidade_id BIGINT NOT NULL,
    tipo_equipamento_id BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    hostname VARCHAR(255),
    ip_address INET NOT NULL,
    fabricante VARCHAR(100),
    modelo VARCHAR(150),
    numero_serie VARCHAR(150),
    descricao TEXT,
    localizacao VARCHAR(255),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_equipamento PRIMARY KEY (id),
    CONSTRAINT ck_equipamento_nome_nao_vazio CHECK (btrim(nome) <> ''),
    -- INET aceita prefixo de rede: '192.168.1.10' e '192.168.1.10/24' sao
    -- valores DIFERENTES para o indice unico, apesar de designarem o mesmo
    -- host. Sem esta checagem o mesmo equipamento entra duas vezes na mesma
    -- unidade. Aqui so cabe endereco de host: /32 em IPv4, /128 em IPv6.
    CONSTRAINT ck_equipamento_ip_e_host CHECK (
        masklen(ip_address) = CASE family(ip_address) WHEN 4 THEN 32 ELSE 128 END
    ),
    CONSTRAINT fk_equipamento_unidade FOREIGN KEY (unidade_id)
        REFERENCES unidade (id) ON DELETE RESTRICT,
    CONSTRAINT fk_equipamento_tipo_equipamento FOREIGN KEY (tipo_equipamento_id)
        REFERENCES tipo_equipamento (id) ON DELETE RESTRICT
);

-- Unicidade de IP por unidade, nao global: unidades distintas usam as mesmas
-- faixas privadas. Vale somente entre registros nao excluidos.
CREATE UNIQUE INDEX uq_equipamento_unidade_ip ON equipamento (unidade_id, ip_address) WHERE deleted_at IS NULL;

-- Mesmo criterio para o nome do equipamento dentro da unidade.
CREATE UNIQUE INDEX uq_equipamento_unidade_nome ON equipamento (unidade_id, LOWER(nome)) WHERE deleted_at IS NULL;

-- Equipamentos por unidade e por tipo.
--
-- Estes dois indices NAO podem ser parciais. A verificacao do ON DELETE
-- RESTRICT executa "SELECT 1 FROM equipamento WHERE <fk> = $1 FOR KEY SHARE",
-- sem predicado de deleted_at: um indice com WHERE deleted_at IS NULL nao pode
-- ser usado ali e o PostgreSQL cai em seq scan a cada exclusao de unidade ou
-- de tipo. Sendo totais, atendem tanto a integridade referencial quanto as
-- consultas de aplicacao, que apenas somam o filtro deleted_at IS NULL.
CREATE INDEX ix_equipamento_unidade ON equipamento (unidade_id);

CREATE INDEX ix_equipamento_tipo_equipamento ON equipamento (tipo_equipamento_id);

-- Busca por IP independente da unidade (ex.: "quem responde neste endereco?").
-- Aqui o indice parcial se justifica: nenhuma verificacao de FK depende dele.
CREATE INDEX ix_equipamento_ip ON equipamento (ip_address) WHERE deleted_at IS NULL;

