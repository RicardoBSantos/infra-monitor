-- V5 - Configuracao de monitores por equipamento.
CREATE TABLE monitor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    equipamento_id BIGINT NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    intervalo_segundos INTEGER NOT NULL,
    timeout_ms INTEGER NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_monitor PRIMARY KEY (id),
    CONSTRAINT ck_monitor_nome_nao_vazio CHECK (btrim(nome) <> ''),
    CONSTRAINT ck_monitor_intervalo_faixa CHECK (intervalo_segundos BETWEEN 10 AND 86400),
    CONSTRAINT ck_monitor_timeout_faixa CHECK (timeout_ms BETWEEN 100 AND 60000),
    CONSTRAINT fk_monitor_equipamento FOREIGN KEY (equipamento_id)
        REFERENCES equipamento (id) ON DELETE RESTRICT
);

-- Consultas de monitores por equipamento sao frequentes e este indice tambem
-- atende a verificacao da FK ao excluir um equipamento.
CREATE INDEX ix_monitor_equipamento ON monitor (equipamento_id);
