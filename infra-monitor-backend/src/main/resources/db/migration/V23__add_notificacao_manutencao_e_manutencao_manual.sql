-- V23 - Telegram da manutencao agendada e do botao manual (F3).
--
-- manutencao_manual: sessao do botao (ancora de notificacao e historico: quem ligou, quem
-- desligou, duracao). Uma sessao aberta por equipamento. Equipamentos que ja estao no botao
-- ganham sessao aberta SEM inicio e SEM autor: NULL honesto, now() inventaria um periodo.
-- notificacao ganha duas ancoras novas (janela e sessao manual): exatamente uma das quatro.
-- Desenho: Docs/superpowers/specs/2026-10-26-manutencao-agendada-f3-design.md

CREATE TABLE manutencao_manual (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL REFERENCES equipamento(id) ON DELETE RESTRICT,
    iniciada_em TIMESTAMPTZ,
    iniciada_por_id BIGINT REFERENCES usuarios(id) ON DELETE RESTRICT,
    encerrada_em TIMESTAMPTZ,
    encerrada_por_id BIGINT REFERENCES usuarios(id) ON DELETE RESTRICT,
    -- Sessao sem inicio e so a do backfill: sem autor tambem. Nunca o contrario (autor sem instante).
    CONSTRAINT ck_manutencao_manual_legado CHECK (iniciada_em IS NOT NULL OR iniciada_por_id IS NULL),
    CONSTRAINT ck_manutencao_manual_periodo CHECK (
        encerrada_em IS NULL OR iniciada_em IS NULL OR encerrada_em >= iniciada_em),
    CONSTRAINT ck_manutencao_manual_encerrador CHECK (encerrada_por_id IS NULL OR encerrada_em IS NOT NULL)
);

CREATE UNIQUE INDEX uq_manutencao_manual_aberta ON manutencao_manual (equipamento_id)
    WHERE encerrada_em IS NULL;
CREATE INDEX ix_manutencao_manual_equipamento ON manutencao_manual (equipamento_id, id DESC);

-- Backfill: equipamentos hoje no botao. Mesmo principio da V19.
INSERT INTO manutencao_manual (equipamento_id)
SELECT id FROM equipamento WHERE manutencao_manual;

ALTER TABLE notificacao ADD COLUMN manutencao_agendada_id BIGINT;
ALTER TABLE notificacao ADD CONSTRAINT fk_notificacao_manutencao_agendada
    FOREIGN KEY (manutencao_agendada_id) REFERENCES manutencao_agendada(id) ON DELETE RESTRICT;
ALTER TABLE notificacao ADD COLUMN manutencao_manual_id BIGINT;
ALTER TABLE notificacao ADD CONSTRAINT fk_notificacao_manutencao_manual
    FOREIGN KEY (manutencao_manual_id) REFERENCES manutencao_manual(id) ON DELETE RESTRICT;

-- CHECK nao se estende: e preciso recriar. Mesmo idioma de V15 e V19.
ALTER TABLE notificacao DROP CONSTRAINT ck_notificacao_ancora_exclusiva;
ALTER TABLE notificacao ADD CONSTRAINT ck_notificacao_ancora_exclusiva CHECK (
    num_nonnulls(incidente_id, episodio_latencia_id, manutencao_agendada_id, manutencao_manual_id) = 1
);

ALTER TABLE notificacao DROP CONSTRAINT ck_notificacao_tipo_evento;
ALTER TABLE notificacao ADD CONSTRAINT ck_notificacao_tipo_evento CHECK (
    tipo_evento IN ('INCIDENTE_ABERTO', 'INCIDENTE_FECHADO',
                    'LATENCIA_ALTA', 'LATENCIA_NORMALIZADA',
                    'INCIDENTE_ENCERRADO_MANUTENCAO', 'LATENCIA_ENCERRADA_MANUTENCAO',
                    'MANUTENCAO_INICIADA', 'MANUTENCAO_ENCERRADA', 'MANUTENCAO_FIM_ALTERADO',
                    'MANUTENCAO_MANUAL_INICIADA', 'MANUTENCAO_MANUAL_ENCERRADA')
);

-- Os dois primeiros ramos sao os da V19, literalmente.
ALTER TABLE notificacao DROP CONSTRAINT ck_notificacao_evento_coerente;
ALTER TABLE notificacao ADD CONSTRAINT ck_notificacao_evento_coerente CHECK (
    (tipo_evento IN ('INCIDENTE_ABERTO', 'INCIDENTE_FECHADO', 'INCIDENTE_ENCERRADO_MANUTENCAO')
     AND incidente_id IS NOT NULL)
    OR (tipo_evento IN ('LATENCIA_ALTA', 'LATENCIA_NORMALIZADA', 'LATENCIA_ENCERRADA_MANUTENCAO')
        AND episodio_latencia_id IS NOT NULL)
    OR (tipo_evento IN ('MANUTENCAO_INICIADA', 'MANUTENCAO_ENCERRADA', 'MANUTENCAO_FIM_ALTERADO')
        AND manutencao_agendada_id IS NOT NULL)
    OR (tipo_evento IN ('MANUTENCAO_MANUAL_INICIADA', 'MANUTENCAO_MANUAL_ENCERRADA')
        AND manutencao_manual_id IS NOT NULL)
);

-- Inicio e fim: um por janela. FIM_ALTERADO repete (varias prorrogacoes): a guarda e o CAS de
-- versao na mesma transacao.
CREATE UNIQUE INDEX uq_notificacao_manutencao_evento
    ON notificacao (manutencao_agendada_id, canal, tipo_evento)
    WHERE tipo_evento <> 'MANUTENCAO_FIM_ALTERADO';
ALTER TABLE notificacao ADD CONSTRAINT uq_notificacao_manual_canal_evento
    UNIQUE (manutencao_manual_id, canal, tipo_evento);
CREATE INDEX ix_notificacao_manutencao_agendada_id ON notificacao (manutencao_agendada_id);
CREATE INDEX ix_notificacao_manutencao_manual_id ON notificacao (manutencao_manual_id);
