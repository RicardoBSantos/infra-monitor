-- V6 - Historico imutavel de medicoes executadas pelos monitores.
CREATE TABLE medicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    monitor_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    latencia_ms INTEGER,
    mensagem VARCHAR(255),
    executado_em TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_medicao PRIMARY KEY (id),
    CONSTRAINT ck_medicao_status CHECK (status IN ('SUCESSO', 'FALHA')),
    CONSTRAINT ck_medicao_latencia_nao_negativa
        CHECK (latencia_ms IS NULL OR latencia_ms >= 0),
    CONSTRAINT ck_medicao_falha_sem_latencia
        CHECK (status = 'SUCESSO' OR latencia_ms IS NULL),
    CONSTRAINT fk_medicao_monitor FOREIGN KEY (monitor_id)
        REFERENCES monitor (id) ON DELETE RESTRICT
);

-- Historico e ultima medicao de um monitor.
CREATE INDEX ix_medicao_monitor_executado_em ON medicao (monitor_id, executado_em DESC);

-- Consultas por periodo e a ordenacao global mais recente primeiro usam este indice.
CREATE INDEX ix_medicao_executado_em ON medicao (executado_em DESC);
