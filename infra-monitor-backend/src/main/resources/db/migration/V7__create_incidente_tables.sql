-- V7 - Historico operacional de incidentes por monitor.
CREATE TABLE incidente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    monitor_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    iniciado_em TIMESTAMPTZ NOT NULL,
    encerrado_em TIMESTAMPTZ,
    motivo VARCHAR(255),
    observacao VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_incidente PRIMARY KEY (id),
    CONSTRAINT ck_incidente_status CHECK (status IN ('ABERTO', 'FECHADO')),
    CONSTRAINT ck_incidente_ciclo_vida CHECK (
        (status = 'ABERTO' AND encerrado_em IS NULL)
        OR (status = 'FECHADO' AND encerrado_em IS NOT NULL)
    ),
    CONSTRAINT ck_incidente_encerramento_posterior CHECK (
        encerrado_em IS NULL OR encerrado_em >= iniciado_em
    ),
    CONSTRAINT fk_incidente_monitor FOREIGN KEY (monitor_id)
        REFERENCES monitor (id) ON DELETE RESTRICT
);

-- Garante a regra tambem sob concorrencia, alem da validacao de negocio.
CREATE UNIQUE INDEX uq_incidente_monitor_aberto ON incidente (monitor_id)
    WHERE status = 'ABERTO';

-- Atende o historico de um monitor e sua ordenacao padrao.
CREATE INDEX ix_incidente_monitor_iniciado_em ON incidente (monitor_id, iniciado_em DESC);

-- Atende listagens globais e filtros por status em ordem cronologica.
CREATE INDEX ix_incidente_status_iniciado_em ON incidente (status, iniciado_em DESC);
