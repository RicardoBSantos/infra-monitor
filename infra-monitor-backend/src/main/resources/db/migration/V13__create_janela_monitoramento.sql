CREATE TABLE janela_monitoramento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monitor_id BIGINT NOT NULL REFERENCES monitor(id) ON DELETE RESTRICT,
    inicio_em TIMESTAMPTZ NOT NULL,
    fim_em TIMESTAMPTZ,
    origem VARCHAR(12) NOT NULL,
    CONSTRAINT ck_janela_monitoramento_periodo CHECK (fim_em IS NULL OR fim_em >= inicio_em),
    CONSTRAINT ck_janela_monitoramento_origem CHECK (origem IN ('PRECISA', 'INFERIDA'))
);
CREATE UNIQUE INDEX uq_janela_monitoramento_aberta ON janela_monitoramento(monitor_id) WHERE fim_em IS NULL;
CREATE INDEX ix_janela_monitoramento_monitor_periodo ON janela_monitoramento(monitor_id, inicio_em, fim_em);

-- Backfill deterministico: nunca abre uma janela historica e nunca usa updated_at.
INSERT INTO janela_monitoramento(monitor_id, inicio_em, fim_em, origem)
SELECT m.id, GREATEST(m.created_at, x.primeira), x.ultima + make_interval(secs => m.intervalo_segundos), 'INFERIDA'
FROM monitor m
JOIN LATERAL (SELECT min(executado_em) primeira, max(executado_em) ultima FROM medicao md WHERE md.monitor_id=m.id) x ON x.primeira IS NOT NULL;
